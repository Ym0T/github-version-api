//! Download of generated diff archives.
use std::sync::Arc;
use std::time::SystemTime;

use axum::body::Body;
use axum::extract::rejection::PathRejection;
use axum::extract::{Path, State};
use axum::http::{HeaderValue, header};
use axum::response::Response;
use tokio_util::io::ReaderStream;

use crate::error::ApiError;
use crate::services::cleanup;
use crate::state::AppState;
use crate::utils::fs::open_nofollow;
use crate::validation::is_valid_zip_filename;

/// `GET /download/diff/{filename}`
pub async fn download_diff_file(
    State(state): State<Arc<AppState>>,
    path: Result<Path<String>, PathRejection>,
) -> Result<Response, ApiError> {
    let Path(filename) = path?;
    // Only names generated by this service are accepted, so the path can't
    // point anywhere outside the archive directory.
    if !is_valid_zip_filename(&filename) {
        return Err(ApiError::bad_request(
            "invalid_filename",
            "Invalid archive name",
        ));
    }
    let not_found = || ApiError::not_found("file_not_found", "Archive not found or expired");

    // Open without following symlinks and check the opened file itself, so
    // there is no gap between check and use.
    let Ok(file) = open_nofollow(&state.config.diffs_dir.join(&filename)).await else {
        return Err(not_found());
    };
    let meta = file
        .metadata()
        .await
        .map_err(|e| ApiError::internal("cannot stat archive", e))?;
    if !meta.is_file() || cleanup::age(&meta, SystemTime::now()) >= state.config.zip.retention {
        return Err(not_found());
    }

    let disposition = HeaderValue::from_str(&format!("attachment; filename=\"{filename}\""))
        .map_err(|e| ApiError::internal("invalid content disposition", e))?;
    Response::builder()
        .header(header::CONTENT_TYPE, "application/zip")
        .header(header::CONTENT_LENGTH, meta.len())
        .header(header::CONTENT_DISPOSITION, disposition)
        .header(header::CACHE_CONTROL, "private, max-age=3600")
        .body(Body::from_stream(ReaderStream::new(file)))
        .map_err(|e| ApiError::internal("cannot build download response", e))
}
